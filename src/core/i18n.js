let lang = 'fr';
try { lang = localStorage.getItem('sc.lang') || (navigator.language || 'fr').slice(0, 2); } catch (e) { /* storage unavailable */ }
if (!STRINGS[lang]) lang = 'en';

export const LANGS = ['fr', 'en'];
export function getLang() { return lang; }
export function setLang(l) {
  lang = STRINGS[l] ? l : 'fr';
  try { localStorage.setItem('sc.lang', lang); } catch (e) { /* ignore */ }
}

export function t(key, ...args) {
  let s = STRINGS[lang][key] ?? STRINGS.fr[key] ?? key;
  if (typeof s === 'string') args.forEach((a, i) => { s = s.replace(`{${i}}`, a); });
  return s;
}
